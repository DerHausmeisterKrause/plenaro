-- Encryption key is NEVER stored in PostgreSQL.
-- User secrets are scoped to an Identity user; global secrets require Admin role.
CREATE TABLE encrypted_secrets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope varchar(8) NOT NULL CHECK (scope IN ('user','global')),
  owner_user_id uuid REFERENCES "AspNetUsers"("Id") ON DELETE CASCADE,
  secret_name varchar(64) NOT NULL,
  ciphertext bytea NOT NULL,
  nonce bytea NOT NULL CHECK (octet_length(nonce) = 12),
  auth_tag bytea NOT NULL CHECK (octet_length(auth_tag) = 16),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_vault_owner CHECK (
    (scope='global' AND owner_user_id IS NULL) OR
    (scope='user' AND owner_user_id IS NOT NULL)
  )
);
CREATE UNIQUE INDEX ux_vault_global ON encrypted_secrets(secret_name) WHERE scope='global';
CREATE UNIQUE INDEX ux_vault_personal ON encrypted_secrets(owner_user_id,secret_name) WHERE scope='user';
